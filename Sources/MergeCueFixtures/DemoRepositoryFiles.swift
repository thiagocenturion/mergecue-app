    static let chargeServiceHead = #"""
        import Foundation

        /// A card charge request coming from the checkout API.
        public struct ChargeRequest: Sendable, Equatable {
            public var requestID: String
            public var customerID: String
            public var cardNumber: String
            public var amountCents: Int
            public var currency: String

            public init(requestID: String, customerID: String, cardNumber: String, amountCents: Int, currency: String = "USD") {
                self.requestID = requestID
                self.customerID = customerID
                self.cardNumber = cardNumber
                self.amountCents = amountCents
                self.currency = currency
            }
        }

        public enum ChargeError: Error, Equatable {
            case invalidAmount
            case declined(String)
            case gatewayTimeout
        }

        /// The outcome of a successful charge.
        public struct ChargeReceipt: Sendable, Equatable {
            public var chargeID: String
            /// Gateway calls it took (1 = no retry).
            public var attempts: Int

            public init(chargeID: String, attempts: Int) {
                self.chargeID = chargeID
                self.attempts = attempts
            }
        }

        /// Where the service writes operational logs.
        public protocol PaymentLogger: Sendable {
            func info(_ message: String)
        }

        public struct PrintLogger: PaymentLogger {
            public init() {}
            public func info(_ message: String) { print(message) }
        }

        /// Charges cards through the gateway, retrying gateway timeouts.
        ///
        /// Every attempt of one request reuses the request id as the idempotency key, so a timeout after the gateway
        /// accepted the charge can never charge the customer twice.
        public struct ChargeService: Sendable {
            let gateway: any PaymentGateway
            let retryPolicy: RetryPolicy
            let logger: any PaymentLogger

            public init(
                gateway: any PaymentGateway,
                retryPolicy: RetryPolicy = RetryPolicy(),
                logger: any PaymentLogger = PrintLogger()
            ) {
                self.gateway = gateway
                self.retryPolicy = retryPolicy
                self.logger = logger
            }

            /// Charges `request`, retrying timeouts up to `retryPolicy.maxRetries` times.
            ///
            /// Retries wait `retryPolicy.delayNanoseconds(forAttempt:)` between attempts (exponential backoff).
            /// Declines are never retried: the gateway already answered, so retrying would only repeat the decline.
            ///
            /// - Parameter request: The charge to perform. `requestID` doubles as the idempotency key.
            /// - Returns: The gateway's charge id and the number of attempts it took.
            /// - Throws: `ChargeError.invalidAmount` for non-positive amounts, `ChargeError.gatewayTimeout` when
            ///   every attempt timed out, or the gateway's error.
            public func charge(_ request: ChargeRequest) async throws -> ChargeReceipt {
                guard request.amountCents > 0 else { throw ChargeError.invalidAmount }
                var attempt = 0
                while true {
                    attempt += 1
                    // Operational log line for support: which card, how much, which attempt.
                    let amount = "\(request.amountCents) \(request.currency)"
                    let context = "request \(request.requestID), attempt \(attempt)"
                    logger.info("Charging card \(request.cardNumber) for \(amount) (\(context))")
                    do {
                        let chargeID = try await gateway.charge(request, idempotencyKey: request.requestID)
                        return ChargeReceipt(chargeID: chargeID, attempts: attempt)
                    } catch ChargeError.gatewayTimeout where attempt <= retryPolicy.maxRetries {
                        try await Task.sleep(nanoseconds: retryPolicy.delayNanoseconds(forAttempt: attempt))
                    }
                }
            }
        }

        """#

    static let retryPolicy = #"""
        import Foundation

        /// How often and how fast `ChargeService` retries gateway timeouts.
        public struct RetryPolicy: Sendable, Equatable {
            /// Base delay before the first retry, in milliseconds.
            public var baseDelayMilliseconds: UInt64

            public init(baseDelayMilliseconds: UInt64 = 200) {
                self.baseDelayMilliseconds = baseDelayMilliseconds
            }

            public var maxRetries: Int {
                let maxRetries = 3
                return maxRetries
            }

            /// Exponential backoff: base, 2 × base, 4 × base, …
            public func delayNanoseconds(forAttempt attempt: Int) -> UInt64 {
                let factor = UInt64(1) << UInt64(max(0, min(attempt - 1, 10)))
                return baseDelayMilliseconds * factor * 1_000_000
            }
        }

        """#

