          # Charges a card through the gateway (legacy Ruby worker).
          class Charge
            MAX_ATTEMPTS = 5

            def initialize(gateway:, logger:)
              @gateway = gateway
              @logger = logger
            end

            def call(params)
              amount_cents = params.fetch(:amount_cents).to_i
              attempts = 0
              begin
                attempts += 1
                @gateway.charge(amount_cents: amount_cents, idempotency_key: params.fetch(:request_id))
              rescue Gateway::Timeout
                retry if attempts < MAX_ATTEMPTS
                raise
              end
            end
          end
        end

